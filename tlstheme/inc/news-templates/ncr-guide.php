        <h3>NCR Claim Conditions Under Sabah Land Ordinance Section 15</h3>
        <p>The Sabah Land Ordinance 1930 is a critical piece of legislation that governs land ownership in the state. For native Sabahans, Section 15 provides a pathway to claiming Native Customary Rights (NCR). Understanding these conditions is essential for any land investor or developer looking to operate in Sabah.</p>
        
        <p>There are seven distinct conditions under which an NCR claim can be made. Each condition has its own set of requirements and evidentiary standards. Below is a detailed breakdown of these conditions based on 2020 statistics.</p>
        
