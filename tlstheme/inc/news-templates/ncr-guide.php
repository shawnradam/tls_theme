    <h4>Key Takeaways for Investors</h4>
    <ul>
        <li><strong>Customary tenure</strong> requires continuous occupation or cultivation for 3+ consecutive years</li>
        <li>NT land can only be traded among native Sabahans unless state government permission granted</li>
        <li>The Sabah Native Land Services Programme (PANTAS) accelerates title issuance within 12 months</li>
    </ul>
